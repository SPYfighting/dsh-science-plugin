import { constants, copyFileSync, linkSync, lstatSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { randomUUID } from 'node:crypto'

// Each component is a directory we own inside the caller's workspace.
// Reject a redirected directory before creating anything below it.
function archiveDirectory(parent, name) {
  const dir = join(parent, name)
  mkdirSync(dir, { recursive: true })
  if (!lstatSync(dir).isDirectory()) throw new Error(`报告目录必须是普通目录：${dir}`)
  return dir
}

function publishNewFile(temp, path) {
  try {
    linkSync(temp, path)
  } catch (error) {
    // Removable drives and some network shares do not support hard links.
    if (!['EOPNOTSUPP', 'ENOTSUP', 'ENOSYS', 'EPERM', 'EMLINK', 'EXDEV'].includes(error.code)) throw error
    copyFileSync(temp, path, constants.COPYFILE_EXCL)
  }
}

export function saveBlueprintReport(cwd, projectId, revision, markdown) {
  // Project IDs are generated by the store, never use a title as a path.
  if (projectId && !/^[A-Za-z0-9_-]+$/.test(projectId)) throw new Error('报告项目编号无效')
  if (!Number.isSafeInteger(revision) || revision < 0) throw new Error('报告修订号无效')
  const research = archiveDirectory(cwd, 'research')
  const root = archiveDirectory(research, 'blueprints')
  const dir = archiveDirectory(root, projectId || 'unbound')
  const temp = join(dir, `.export-${randomUUID()}.tmp`)
  const content = Buffer.from(markdown)
  let path
  let reused = false
  try {
    writeFileSync(temp, content, { flag: 'wx' })
    for (let copy = 1; ; copy++) {
      path = join(dir, `blueprint-r${revision}${copy === 1 ? '' : '-' + copy}.md`)
      try {
        // Publish the complete file atomically. Concurrent exports cannot
        // replace an existing revision or mistake a partial write for an edit.
        publishNewFile(temp, path)
        break
      } catch (error) {
        if (error.code !== 'EEXIST') throw error
        const existing = lstatSync(path, { throwIfNoEntry: false })
        if (existing?.isFile() && existing.size === content.length && readFileSync(path).equals(content)) {
          reused = true
          break
        }
      }
    }
  } finally {
    try { unlinkSync(temp) } catch (error) { if (error.code !== 'ENOENT') throw error }
  }

  // Older integrations read this fixed name. Keep the first copy independent
  // of the archive, so editing either file cannot change the other.
  const legacyPath = join(research, 'blueprint-report.md')
  try {
    copyFileSync(path, legacyPath, constants.COPYFILE_EXCL)
  } catch (error) {
    if (error.code !== 'EEXIST') throw error
  }
  return { path, revision, reused }
}
